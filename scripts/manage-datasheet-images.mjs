import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,dirname,relative,extname} from 'node:path';
import {createRequire} from 'node:module';

const root=resolve(import.meta.dirname,'..');
const manifestPath=resolve(root,'data/datasheet-image-manifest.json');
const generatedPath=resolve(root,'datasheet-images.generated.js');
const require=createRequire(import.meta.url);
const existing=require(resolve(root,'datasheet-images.js'));
const manifest=JSON.parse(await readFile(manifestPath,'utf8'));
const entries=[...manifest.units,...manifest.models];
const command=process.argv[2]||'status';
const save=()=>writeFile(manifestPath,JSON.stringify(manifest,null,2)+'\n','utf8');
const localFile=path=>resolve(root,path);
const safeName=value=>String(value).replace(/[^a-zA-Z0-9_-]/g,'_');
const mimeExtensions={'image/jpeg':'.jpg','image/png':'.png','image/webp':'.webp','image/avif':'.avif','image/gif':'.gif'};

if(command==='seed'){
  for(const entry of manifest.units){if(entry.photo)continue;const photo=existing.unitPhoto({id:entry.id});if(photo)entry.photo={...(photo.src.startsWith('http')?{url:photo.src}:{localPath:photo.src}),source:photo.source||''};}
  for(const entry of manifest.models){if(entry.photo)continue;const photo=existing.modelPhoto({id:entry.unitId},{id:entry.id});if(photo)entry.photo={...(photo.src.startsWith('http')?{url:photo.src}:{localPath:photo.src}),source:photo.source||''};}
  await save();
}
if(command==='download'){
  const byHash=new Map(entries.filter(e=>e.photo?.sha256&&e.photo?.localPath).map(e=>[e.photo.sha256,e.photo.localPath]));
  let saved=0,failed=0;
  for(const entry of entries){
    const photo=entry.photo;
    if(!photo?.url||photo.localPath)continue;
    try{
      const url=new URL(photo.url);
      if(url.protocol!=='https:')throw Error('HTTPS 이미지 URL만 허용합니다.');
      const response=await fetch(url,{signal:AbortSignal.timeout(20000),headers:{'User-Agent':'WarHamImageCatalog/1.0'}});
      if(!response.ok)throw Error(`HTTP ${response.status}`);
      const type=(response.headers.get('content-type')||'').split(';')[0].toLowerCase();
      const extension=mimeExtensions[type];
      if(!extension)throw Error(`이미지가 아닌 응답: ${type}`);
      const bytes=Buffer.from(await response.arrayBuffer());
      if(bytes.length<200||bytes.length>15_000_000)throw Error(`허용 범위를 벗어난 크기: ${bytes.length}`);
      const sha256=createHash('sha256').update(bytes).digest('hex');
      let path=byHash.get(sha256);
      if(!path){
        const basename=entry.unitId?`${safeName(entry.unitId)}__${safeName(entry.id)}`:safeName(entry.id);
        path=`images/datasheets/by-id/${basename}${extension}`;
        await mkdir(dirname(localFile(path)),{recursive:true});
        await writeFile(localFile(path),bytes,{flag:'wx'});
        byHash.set(sha256,path);
      }
      photo.localPath=path;photo.sha256=sha256;photo.bytes=bytes.length;photo.contentType=type;
      await save();saved++;
    }catch(error){failed++;console.error(`${entry.id}: ${error.message}`);}
  }
  console.log(`저장 ${saved}개 · 실패 ${failed}개`);
  if(failed)process.exitCode=1;
}
if(command==='build'){
  const output={units:{},models:{}};
  for(const entry of manifest.units){const path=entry.photo?.localPath;if(path&&await stat(localFile(path)).then(x=>x.isFile()).catch(()=>false))output.units[entry.id]={src:path,source:entry.photo.source||''};}
  for(const entry of manifest.models){const path=entry.photo?.localPath;if(path&&await stat(localFile(path)).then(x=>x.isFile()).catch(()=>false))output.models[`${entry.unitId}:${entry.id}`]=path;}
  await writeFile(generatedPath,`// Generated by scripts/manage-datasheet-images.mjs build\nglobalThis.DatasheetImageFiles=${JSON.stringify(output)};\n`,'utf8');
  console.log(`앱 연결: 유닛 ${Object.keys(output.units).length}개 · 모델 ${Object.keys(output.models).length}개`);
}
if(command==='status'||command==='seed'){
  const count=list=>({total:list.length,linked:list.filter(x=>x.photo?.url||x.photo?.localPath).length,downloaded:list.filter(x=>x.photo?.localPath).length});
  console.log(JSON.stringify({units:count(manifest.units),models:count(manifest.models)},null,2));
}
if(!['status','seed','download','build'].includes(command))throw Error('명령: status | seed | download | build');
